// clientKeyHeader returns the client key from the X-Client-Key header,
// accepting the Supabase-compatible `apikey` header as a fallback.
// Query parameters are not accepted (removed for security).
func clientKeyHeader(c fiber.Ctx) string {
	if key := c.Get("X-Client-Key"); key != "" {
		return key
	}
	return c.Get("apikey")
}

// ClientKeyAuth creates middleware that authenticates requests using client keys
// Client key must be provided via X-Client-Key (or apikey) header (query parameter removed for security)
func ClientKeyAuth(clientKeyService *auth.ClientKeyService) fiber.Handler {
	return func(c fiber.Ctx) error {
		clientKey := clientKeyHeader(c)

		// If no client key provided, return unauthorized
		if clientKey == "" {
			return apperrors.SendErrorWithCode(c, 401, "Missing client key. Provide via X-Client-Key or apikey header", apperrors.ErrCodeMissingClientKey)
		}

		// Validate the client key
		validatedKey, err := clientKeyService.ValidateClientKey(c.RequestCtx(), clientKey)
		if err != nil {
			log.Debug().Err(err).Msg("Invalid client key")

			// Return specific error messages using errors.Is for proper error wrapping
			if errors.Is(err, auth.ErrClientKeyRevoked) {
				return apperrors.SendErrorWithCode(c, 401, "Client key has been revoked", apperrors.ErrCodeClientKeyRevoked)
			}
			if errors.Is(err, auth.ErrClientKeyExpired) {
				return apperrors.SendErrorWithCode(c, 401, "Client key has been expired", apperrors.ErrCodeClientKeyExpired)
			}
			if errors.Is(err, auth.ErrUserClientKeysDisabled) {
				return apperrors.SendErrorWithCode(c, 403, "User client keys are disabled. Contact an administrator.", apperrors.ErrCodeClientKeysDisabled)
			}

			return apperrors.SendErrorWithCode(c, 401, "Invalid client key", apperrors.ErrCodeInvalidCredentials)
		}

		// Store client key information in context
		c.Locals("client_key_id", validatedKey.ID)
		c.Locals("client_key_name", validatedKey.Name)
		c.Locals("client_key_scopes", validatedKey.Scopes)

		// Store allowed namespaces (nil = all allowed, empty = default only)
		if validatedKey.AllowedNamespaces != nil {
			c.Locals("allowed_namespaces", validatedKey.AllowedNamespaces)
		}

		// If client key is associated with a user, store user ID
		if validatedKey.UserID != nil {
			c.Locals("user_id", *validatedKey.UserID)
		}

		// Continue to next handler
		return c.Next()
	}
}

// isWebSocketUpgrade reports whether the request is an actual WebSocket
// upgrade. Query parameters are only accepted as credentials for WebSocket
// connections (browsers cannot set custom headers on those).
func isWebSocketUpgrade(c fiber.Ctx) bool {
	return strings.EqualFold(c.Get("Upgrade"), "websocket")
}

// validateUserAccessToken validates a bearer token as an app-user access
// token. Refresh tokens are rejected here: they are only accepted at the
// refresh endpoint.
func validateUserAccessToken(authService *auth.Service, token string) (*auth.TokenClaims, error) {
	return authService.JWTManager().ValidateAccessToken(token)
}

// checkTokenRevoked verifies the token is not blacklisted (fail-closed).
func checkTokenRevoked(authService *auth.Service, c fiber.Ctx, claims *auth.TokenClaims) error {
	// IssuedAt is a *NumericDate and is absent from hand-minted tokens (e.g.
	// service keys generated by deploy/generate-keys.sh); dereferencing it
	// unconditionally panics the request. A zero issuedAt only skips the
	// user-wide revocation comparison, the exact-JTI check still runs.
	var issuedAt time.Time
	if claims.IssuedAt != nil {
		issuedAt = claims.IssuedAt.Time
	}
	isRevoked, err := authService.TokenBlacklistService().IsTokenRevoked(c.RequestCtx(), claims.ID, claims.UserID, issuedAt)
	if err != nil {
		return err
	}
	if isRevoked {
		return auth.ErrTokenBlacklisted
	}
	return nil
}

// OptionalClientKeyAuth allows both JWT and client key authentication
// Tries JWT first, then client key
func OptionalClientKeyAuth(authService *auth.Service, clientKeyService *auth.ClientKeyService) fiber.Handler {
	return func(c fiber.Ctx) error {
		// Try JWT authentication first
		authHeader := c.Get("Authorization")
		if authHeader != "" && strings.HasPrefix(authHeader, "Bearer ") {
			token := strings.TrimPrefix(authHeader, "Bearer ")

			// Validate JWT token (access tokens only)
			claims, err := validateUserAccessToken(authService, token)
			if err == nil {
				// Check if token has been revoked
				// SECURITY: Fail-closed behavior - reject if we can't verify revocation status
				if err := checkTokenRevoked(authService, c, claims); err != nil {
					if errors.Is(err, auth.ErrTokenBlacklisted) {
						return apperrors.SendTokenRevoked(c)
					}
					log.Error().Err(err).Str("jti", claims.ID).Msg("Token revocation check failed")
					return apperrors.SendServiceUnavailable(c, "Unable to verify token status")
				}

				// Valid JWT token
				c.Locals("user_id", claims.UserID)
				c.Locals("user_email", claims.Email)
				c.Locals("user_name", claims.Name)
				c.Locals("user_role", claims.Role)
				c.Locals("session_id", claims.SessionID)
				c.Locals("auth_type", "jwt")
				c.Locals("claims", claims)
				c.Locals("jwt_claims", claims)
				return c.Next()
			}
		}

		// Try client key authentication (header only, query parameter removed for security)
		clientKey := clientKeyHeader(c)

		if clientKey != "" {
			validatedKey, err := clientKeyService.ValidateClientKey(c.RequestCtx(), clientKey)
			if err == nil {
				// Valid client key
				c.Locals("client_key_id", validatedKey.ID)
				c.Locals("client_key_name", validatedKey.Name)
				c.Locals("client_key_scopes", validatedKey.Scopes)
				c.Locals("auth_type", "clientkey")

				// Store allowed namespaces
				if validatedKey.AllowedNamespaces != nil {
					c.Locals("allowed_namespaces", validatedKey.AllowedNamespaces)
				}

				if validatedKey.UserID != nil {
					c.Locals("user_id", *validatedKey.UserID)
				}

				return c.Next()
			}
		}

		// No valid authentication provided, continue anyway (optional auth)
		return c.Next()
	}
}

